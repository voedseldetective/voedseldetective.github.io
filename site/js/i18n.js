export const LANGS = ["nl", "en", "tr"];

export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] || STRINGS.nl;
  const s = table[key] ?? STRINGS.nl[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

export function pickLang(navigatorLanguages) {
  for (const l of navigatorLanguages || []) {
    const base = String(l).toLowerCase().split("-")[0];
    if (LANGS.includes(base)) return base;
  }
  return "nl";
}
